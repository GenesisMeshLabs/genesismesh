"""1.11.0: the Network Authority names the contract bundle it was built with.

``/health`` reports ``contract_bundle``: the bundle version (the core version)
and the ``contract_digest`` of ``contract/MANIFEST.json``. An SDK that meets a
field it does not know can then name the newer bundle instead of only
``unknown_field``. Both live in ``genesis_mesh/contract_bundle.py``, written
with the manifest by ``scripts/gm_contract.py manifest``, never read from the
installed distribution's metadata (a source checkout may carry stale metadata).
"""

from __future__ import annotations

import ast
import importlib.util
import json
import re
import shutil
from pathlib import Path

from genesis_mesh.contract_bundle import BUNDLE_VERSION, CONTRACT_DIGEST

REPO_ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("gm_contract", REPO_ROOT / "scripts" / "gm_contract.py")
assert _spec and _spec.loader
gm = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gm)


def _manifest() -> dict:
    return json.loads((REPO_ROOT / "contract" / "MANIFEST.json").read_text(encoding="utf-8"))


def _core_version() -> str:
    return (REPO_ROOT / "VERSION").read_text(encoding="utf-8").strip()


def test_health_names_the_bundle_version_and_contract_digest(client) -> None:
    body = client.get("/health").get_json()
    # Tied to the files, not to genesis_mesh.__version__ (installed metadata).
    assert body["contract_bundle"] == {"bundle_version": _core_version(),
                                       "contract_digest": _manifest()["contract_digest"]}
    # The existing fields are unchanged: the addition is additive.
    assert body["status"] == "healthy"
    assert {"network", "version", "boundary_policies", "evidence_store"} <= set(body)


def test_the_package_carries_the_committed_manifests_version_and_digest() -> None:
    manifest = _manifest()
    assert (BUNDLE_VERSION, CONTRACT_DIGEST) == (manifest["bundle_version"], manifest["contract_digest"])
    assert BUNDLE_VERSION == _core_version()
    assert re.fullmatch(r"sha256:[0-9a-f]{64}", CONTRACT_DIGEST)


def test_the_digest_module_is_exactly_what_the_tool_writes() -> None:
    # Byte for byte, as `manifest --check` compares it (.gitattributes checks it out LF).
    data = (REPO_ROOT / gm.DIGEST_MODULE_PATH).read_bytes()
    assert data == gm.digest_module(BUNDLE_VERSION, CONTRACT_DIGEST)
    # Only constants: nothing a generated file should not carry.
    tree = ast.parse(data)
    assert [type(node).__name__ for node in tree.body] == ["Expr", "Assign", "Assign"]


def test_dashboard_shows_the_contract_bundle(client) -> None:
    model = client.get("/dashboard.json").get_json()
    assert model["contract_bundle"] == client.get("/health").get_json()["contract_bundle"]
    page = client.get("/dashboard").get_data(as_text=True)
    assert "Contract bundle" in page
    assert f'title="{CONTRACT_DIGEST}"' in page
    assert CONTRACT_DIGEST.removeprefix("sha256:")[:12] in page


def test_a_changed_contract_makes_the_package_digest_stale(tmp_path: Path) -> None:
    """``manifest --check`` fails until the digest module is regenerated with the manifest."""
    core = tmp_path / "core"
    for rel in ("VERSION", "contract", "conformance/vectors", "conformance/fixtures", "scripts/gm_contract.py"):
        source = REPO_ROOT / rel
        if source.is_dir():
            shutil.copytree(source, core / rel)
        else:
            (core / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(source, core / rel)
    (core / "genesis_mesh").mkdir()
    shutil.copy(REPO_ROOT / gm.DIGEST_MODULE_PATH, core / gm.DIGEST_MODULE_PATH)
    assert gm.main(["--repo", str(core), "manifest", "--check"]) == 0

    # A vector changes and only the manifest is regenerated by hand: the package digest is stale.
    suite = core / "conformance" / "vectors" / "admin_auth.json"
    data = json.loads(suite.read_text(encoding="utf-8"))
    data["vectors"].append(dict(data["vectors"][0], name="an-added-vector"))
    suite.write_text(json.dumps(data), encoding="utf-8")
    (core / "contract" / "MANIFEST.json").write_bytes(gm.render(gm.build_manifest(core)))
    assert gm.main(["--repo", str(core), "manifest", "--check"]) == 1

    assert gm.main(["--repo", str(core), "manifest"]) == 0
    assert gm.main(["--repo", str(core), "manifest", "--check"]) == 0
    written = (core / gm.DIGEST_MODULE_PATH).read_text(encoding="ascii")
    assert gm.build_manifest(core)["contract_digest"] in written
    assert CONTRACT_DIGEST not in written


def test_a_missing_digest_module_fails_the_check(tmp_path: Path) -> None:
    core = tmp_path / "core"
    shutil.copytree(REPO_ROOT / "contract", core / "contract")
    shutil.copytree(REPO_ROOT / "conformance" / "vectors", core / "conformance" / "vectors")
    shutil.copytree(REPO_ROOT / "conformance" / "fixtures", core / "conformance" / "fixtures")
    (core / "scripts").mkdir()
    shutil.copy(REPO_ROOT / "scripts" / "gm_contract.py", core / "scripts" / "gm_contract.py")
    shutil.copy(REPO_ROOT / "VERSION", core / "VERSION")
    (core / "genesis_mesh").mkdir()
    (core / "contract" / "MANIFEST.json").write_bytes(gm.render(gm.build_manifest(core)))
    assert gm.main(["--repo", str(core), "manifest", "--check"]) == 1


def test_the_tool_refuses_to_write_anything_but_a_version_and_a_digest() -> None:
    version, digest = "1.11.0", "sha256:" + "0" * 64
    assert gm.digest_module(version, digest)
    pairs = [(version, bad) for bad in ("", "sha256:xyz", "sha256:" + "A" * 64, 'sha256:0"\nimport os  #')]
    pairs += [(bad, digest) for bad in ("", "v1.11.0", "1.11", "1.11.0-rc1", '1.11.0"\nimport os  #')]
    for pair in pairs:
        try:
            gm.digest_module(*pair)
        except gm.ContractError:
            continue
        raise AssertionError(f"accepted {pair!r}")
